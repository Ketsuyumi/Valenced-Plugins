/** Each base sound stretched out, short to very long. */
function stretch(): string[] {
	const out: string[] = []
	const grow = (make: (n: number) => string) => {
		for (let n = 1; n <= 7; n++) out.push(make(n))
	}
	grow(n => `me${'o'.repeat(n)}w`)
	grow(n => `m${'e'.repeat(n)}ow`)
	grow(n => `meo${'w'.repeat(n + 1)}`)
	grow(n => `m${'r'.repeat(n + 1)}p`)
	grow(n => `m${'r'.repeat(n)}o${'w'.repeat(n > 3 ? 2 : 1)}`)
	grow(n => `ny${'a'.repeat(n + 1)}`)
	grow(n => `pu${'r'.repeat(n + 2)}`)
	grow(n => `hi${'s'.repeat(n + 2)}`)
	grow(n => `m${'e'.repeat(n)}${'o'.repeat(n)}${'w'.repeat(n)}`)
	grow(n => `MEO${'W'.repeat(n)}${'!'.repeat(Math.min(n, 3))}`)
	return [...new Set(out)]
}

